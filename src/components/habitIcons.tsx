export type HabitIconDef = { name: string; Icon: LucideIcon; cat: IconCat; label: string; words: string[] };

const STOP = new Set(['de', 'du', 'des', 'la', 'le', 'les', 'un', 'une', 'et', 'au', 'aux', 'en', 'pour']);
const norm = (s: string) => s.normalize('NFD').replace(/[\u0300-\u036f]/g, '').replace(/œ/g, 'oe').toLowerCase();
// pluriel simple : « livres » ↔ « livre », « eaux » ↔ « eau »
const stem = (w: string) => (w.length > 3 && /[sx]$/.test(w) ? w.slice(0, -1) : w);
const tokens = (s: string) =>
  norm(s)
    .split(/[^a-z0-9]+/)
    .filter((w) => w.length > 1 && !STOP.has(w))
    .map(stem);
const splitCamel = (s: string) => s.replace(/([a-z])([A-Z0-9])/g, '$1 $2');

export const HABIT_ICONS: HabitIconDef[] = RAW.map(([name, Icon, cat, kw]) => {
  const label = kw.split(' ')[0];
  const catLabel = ICON_CATS.find((c) => c.id === cat)?.label || '';
  return { name, Icon, cat, label, words: [...new Set([...tokens(kw), ...tokens(splitCamel(name)), ...tokens(catLabel)])] };
});

// « Map » est aussi une icône importée : on prend le Map natif
export const ICON_BY_NAME = new globalThis.Map<string, LucideIcon>(HABIT_ICONS.map((e) => [e.name, e.Icon]));

/**
 * Recherche tolérante : sans accents, pluriels, préfixes (« med » → méditation, médicament),
 * mots-clés français ou nom anglais. mode « all » : tous les mots doivent correspondre ; « any » : au moins un.
 */
export function searchIcons(q: string, mode: 'all' | 'any' = 'all'): HabitIconDef[] {
  const qt = tokens(q);
  if (!qt.length) return mode === 'all' ? HABIT_ICONS : [];
  const scored: { e: HabitIconDef; score: number; i: number }[] = [];
  HABIT_ICONS.forEach((e, i) => {
    let score = 0;
    let matched = 0;
    for (const t of qt) {
      let best = 0;
      e.words.forEach((w, wi) => {
        // mot exact > début de mot > milieu de mot (seulement pour les recherches d'au moins 5 lettres)
        let s = w === t ? 3 : w.startsWith(t) ? 2 : mode === 'all' && t.length >= 5 && w.includes(t) ? 1 : 0;
        if (s && wi === 0) s += 1; // le mot principal compte plus
        if (s > best) best = s;
      });
      if (best) {
        matched++;
        score += best;
      } else if (mode === 'all') return;
    }
    if (matched) scored.push({ e, score, i });
  });
  return scored.sort((a, b) => b.score - a.score || a.i - b.i).map((x) => x.e);
}

/** Ce qui représente une habitude : icône choisie, sinon emoji, sinon initiale du nom */
export function habitGlyphKind(h: Pick<Habit, 'icon' | 'emoji'>): 'icon' | 'emoji' | 'letter' {
  if (h.icon && ICON_BY_NAME.has(h.icon)) return 'icon';
  return h.emoji ? 'emoji' : 'letter';
}

export function HabitGlyph({ h, size = 20 }: { h: Pick<Habit, 'icon' | 'emoji' | 'name'>; size?: number }) {
  const Icon = h.icon ? ICON_BY_NAME.get(h.icon) : undefined;
  if (Icon) return <Icon size={size} strokeWidth={2.1} />;
  return <>{h.emoji || h.name.trim().charAt(0).toUpperCase()}</>;
}
